import os
import sqlite3
from contextlib import closing, contextmanager
from pathlib import Path

from .http_app import error

class Database:
    def __init__(self, name):
        self.name = name
        self.dsn = os.getenv("DATABASE_URL")
        self.postgres = bool(self.dsn)
        self.filename = Path(os.getenv("DATA_DIR", "/tmp/repit")) / f"{name}.sqlite3"

    @contextmanager
    def connect(self, write=False):
        if self.postgres:
            import psycopg
            from psycopg.rows import dict_row

            with psycopg.connect(self.dsn, row_factory=dict_row, connect_timeout=2,
                                 options="-c statement_timeout=5000 -c lock_timeout=3000") as connection:
                yield Session(connection, True)
            return
        self.filename.parent.mkdir(parents=True, exist_ok=True)
        with closing(sqlite3.connect(self.filename, timeout=5)) as connection, connection:
            connection.row_factory = sqlite3.Row
            connection.execute("PRAGMA foreign_keys = ON")
            if write:
                connection.execute("BEGIN IMMEDIATE")
            yield Session(connection, False)

    def initialize(self, schema):
        primary_key = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if self.postgres else "INTEGER PRIMARY KEY"
        with self.connect(write=True) as session:
            for sql in schema.replace("AUTO_ID", primary_key).split(";"):
                if sql.strip():
                    session.execute(sql)


class Session:
    def __init__(self, connection, postgres):
        self.connection = connection
        self.postgres = postgres

    def execute(self, sql, args=()):
        return self.connection.execute(sql.replace("?", "%s") if self.postgres else sql, args)

    def all(self, sql, args=()):
        return [dict(row) for row in self.execute(sql, args).fetchall()]

    def one(self, sql, args=(), *, lock=False):
        row = self.execute(sql + (" FOR UPDATE" if lock and self.postgres else ""), args).fetchone()
        return dict(row) if row is not None else None

    def insert(self, table, values):
        columns = ", ".join(values)
        placeholders = ", ".join("?" for _ in values)
        return self.one(f"INSERT INTO {table} ({columns}) VALUES ({placeholders}) RETURNING *", tuple(values.values()))

    def update(self, table, key, values):
        columns = ", ".join(f"{column} = ?" for column in values)
        return self.one(f"UPDATE {table} SET {columns} WHERE id = ? RETURNING *", (*values.values(), key))

    def get(self, table, key, *, lock=False):
        value = self.one(f"SELECT * FROM {table} WHERE id = ?", (key,), lock=lock)
        if value is None:
            error(404, "Запись не найдена.")
        return value

    def serialize_start(self, test_id, student_id):
        if self.postgres:
            key = f"{test_id}:{student_id}"
            self.execute("SELECT pg_advisory_xact_lock(hashtextextended(?, 0))", (key,))
